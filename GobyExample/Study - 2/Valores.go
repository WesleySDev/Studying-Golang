



package main

import "fmt"

func main() {
	//Strings, que podem ser adicionadas junto com +.
	fmt.Println("go" + "lang")


	//Inteiros e flutuantes.
	fmt.Println("1+1 =", 1+1)
	fmt.Println("7.0/3.0 =", 7.0/3.0)

//Booleanos, com operadores booleanos, como seria de se esperar.
	fmt.Println(true && false)
	fmt.Println(true || false)
	fmt.Println(!true)
}